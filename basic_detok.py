#!/usr/bin/env python3
import sys
TOK = {0x80:"END",0x81:"FOR",0x82:"NEXT",0x83:"DATA",0x84:"INPUT#",0x85:"INPUT",0x86:"DIM",0x87:"READ",0x88:"LET",0x89:"GOTO",0x8A:"RUN",0x8B:"IF",0x8C:"RESTORE",0x8D:"GOSUB",0x8E:"RETURN",0x8F:"REM",0x90:"STOP",0x91:"ON",0x92:"WAIT",0x93:"LOAD",0x94:"SAVE",0x95:"VERIFY",0x96:"DEF",0x97:"POKE",0x98:"PRINT#",0x99:"PRINT",0x9A:"CONT",0x9B:"LIST",0x9C:"CLR",0x9D:"CMD",0x9E:"SYS",0x9F:"OPEN",0xA0:"CLOSE",0xA1:"GET",0xA2:"NEW",0xA3:"TAB(",0xA4:"TO",0xA5:"FN",0xA6:"SPC(",0xA7:"THEN",0xA8:"NOT",0xA9:"STEP",0xAA:"+",0xAB:"-",0xAC:"*",0xAD:"/",0xAE:"^",0xAF:"AND",0xB0:"OR",0xB1:">",0xB2:"=",0xB3:"<",0xB4:"SGN",0xB5:"INT",0xB6:"ABS",0xB7:"USR",0xB8:"FRE",0xB9:"POS",0xBA:"SQR",0xBB:"RND",0xBC:"LOG",0xBD:"EXP",0xBE:"COS",0xBF:"SIN",0xC0:"TAN",0xC1:"ATN",0xC2:"PEEK",0xC3:"LEN",0xC4:"STR$",0xC5:"VAL",0xC6:"ASC",0xC7:"CHR$",0xC8:"LEFT$",0xC9:"RIGHT$",0xCA:"MID$",0xCB:"GO",0xFF:"PI"}
CTRL = {0x05:"{wht}",0x0E:"{lower}",0x11:"{down}",0x12:"{rvon}",0x13:"{home}",0x14:"{del}",0x1C:"{red}",0x1D:"{right}",0x1E:"{grn}",0x1F:"{blu}",0x81:"{orng}",0x8E:"{upper}",0x90:"{blk}",0x91:"{up}",0x92:"{rvof}",0x93:"{clr}",0x95:"{brn}",0x96:"{lred}",0x97:"{gry1}",0x98:"{gry2}",0x99:"{lgrn}",0x9A:"{lblu}",0x9B:"{gry3}",0x9C:"{pur}",0x9D:"{left}",0x9E:"{yel}",0x9F:"{cyn}"}
def pet(c):
    if c in CTRL: return CTRL[c]
    if 0x41<=c<=0x5A: return chr(c+0x20)
    if 0xC1<=c<=0xDA: return chr(c-0x80)
    if 0x20<=c<0x7F: return chr(c)
    return "{$%02x}"%c
d=open(sys.argv[1],'rb').read()
p=2
while p+4<=len(d):
    nxt=d[p]|(d[p+1]<<8)
    if nxt==0: break
    ln=d[p+2]|(d[p+3]<<8); p+=4
    out=[]; q=False
    while p<len(d) and d[p]!=0:
        c=d[p]
        if c==0x22: q=not q; out.append('"')
        elif not q and c>=0x80: out.append(TOK.get(c,"{%02x}"%c))
        else: out.append(pet(c))
        p+=1
    p+=1
    print(f"{ln} {''.join(out)}")
print(f"[end at offset {p}, file len {len(d)}]", file=sys.stderr)
